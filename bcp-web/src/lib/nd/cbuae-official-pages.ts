export function isCbuaeRegulationDocName(name?: string | null): boolean {
  if (!name?.trim()) return false;
  const normalized = name.toLowerCase().replace(/\s/g, '');
  return normalized.includes('cbuae') || normalized.includes('3945');
}

export function officialCbuaeViewerPage(
  docName?: string | null,
  pointNumber?: string | null,
): number | null {
  if (!isCbuaeRegulationDocName(docName) || !pointNumber?.trim()) return null;
  const key = pointNumber.trim().replace(/^§\s*/, '').replace(/\.+$/, '');
  const page = CBUAE_OFFICIAL_VIEWER_PAGES[key];
  return page != null && page > 0 ? page : null;
}
